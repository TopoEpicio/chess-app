import { performance } from 'node:perf_hooks'
import { writeFileSync, unlinkSync, readFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const tsPath = path.join(root, 'frontend', 'node_modules', 'typescript', 'lib', 'typescript.js')
const chessPath = path.join(root, 'frontend', 'node_modules', 'chess.js', 'dist', 'esm', 'chess.js').replace(/\\/g, '/')
const chessUrl = pathToFileURL(chessPath).href

const ts = await import(pathToFileURL(tsPath).href)
const { Chess } = await import(chessUrl)

const srcFile = path.join(root, 'frontend', 'src', 'data', 'lichess_openings_generated.ts')
const src = readFileSync(srcFile, 'utf8')

const t0 = performance.now()
let out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 } }).outputText
out = out.replace(/from 'chess\.js'/g, "from '" + chessUrl + "'")
const tmpFile = path.join(root, 'scripts', '.tmp_lichess_openings.mjs')
writeFileSync(tmpFile, out)
const mod = await import(pathToFileURL(tmpFile).href)
unlinkSync(tmpFile)

const lichessOpenings = mod.lichessOpenings
console.log('openings:', lichessOpenings.length)
let vars = 0
const data = []
for (const o of lichessOpenings) {
  const variations = []
  for (const v of o.variations) {
    const game = new Chess()
    const san = []
    for (const uci of v.moves) {
      const m = game.move({ from: uci.slice(0,2), to: uci.slice(2,4), promotion: uci[4] })
      if (!m) throw new Error(`bad move ${uci} in ${o.id}`)
      san.push(m.san)
    }
    variations.push({ name: v.name, moves: san, fen: v.fen })
    vars++
  }
  data.push({ id: o.id, name: o.name, fen: variations[0].fen, eco: o.eco, variations })
}
const t1 = performance.now()
console.log('variations:', vars)

let empty = 0, bad = 0
for (const o of data) for (const v of o.variations) {
  if (v.moves.length === 0) empty++
  for (const m of v.moves) {
    if (!(m === 'O-O' || m === 'O-O-O' || /^[A-Z]/.test(m) || /^[a-h][1-8]/.test(m))) bad++
    if (/^[a-h][1-8][a-h][1-8]/.test(m)) bad++
  }
}
console.log('empty:', empty, 'bad moves:', bad)

const outPath = path.join(root, 'frontend', 'src', 'data', 'openings_precompiled.ts')
const content = "// AUTO-GENERATED by scripts/generate_openings_precompiled.mjs — do not edit by hand.\nexport interface OpeningVariation { name: string; moves: string[]; fen: string }\nexport interface Opening { id: string; name: string; fen: string; eco?: string; variations: OpeningVariation[] }\nexport const openings: Opening[] = " + JSON.stringify(data) + "\n"
writeFileSync(outPath, content)
console.log('written', outPath)

const names = ['Italian Game','Sicilian Defense','French Defense','Caro-Kann Defense',"Queen's Gambit Declined"]
for (const n of names) {
  const o = data.find(x => x.name === n)
  if (o) console.log(JSON.stringify({id:o.id,name:o.name,eco:o.eco,moves:o.variations[0].moves,fen:o.variations[0].fen}))
}

console.log('gen ms:', (t1-t0).toFixed(1))

const generatedSrc = readFileSync(outPath, 'utf8')
const js = ts.transpileModule(generatedSrc, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 } }).outputText
const tmpJs = path.join(root, 'scripts', '.tmp_precompiled.mjs')
writeFileSync(tmpJs, js)
const t2 = performance.now()
const m2 = await import(pathToFileURL(tmpJs).href)
const t3 = performance.now()
console.log('import ms:', (t3-t2).toFixed(1), 'count:', m2.openings.length)
unlinkSync(tmpJs)
